#include <iostream> // Подключение библиотеки для ввода и вывода данных
#include <clocale> // Подключение библиотеки для работы с локалью
#include <cstdlib> // Подключение библиотеки для функций rand() и srand()
#include <ctime> // Подключение библиотеки для функции time()
#include <optional> // Подключение библиотеки для использования std::optional
#include <SFML/Graphics.hpp> // Подключение библиотеки SFML для графики
#include <windows.h> // Подключение библиотеки для настройки кодировки консоли
const int height = 600; // Задание высоты графического окна
const int width = 800; // Задание ширины графического окна
int main() { // Начало главной функции программы
    const int CODEPAGE = 1251; // Задание кодировки Windows-1251
    SetConsoleCP(CODEPAGE); // Установка кодировки ввода консоли
    SetConsoleOutputCP(CODEPAGE); // Установка кодировки вывода консоли
    int count = 0; // Переменная для подсчёта непересекающихся окружностей
    int n; // Переменная для хранения количества окружностей
    int r; // Переменная для хранения радиуса окружностей
    setlocale(LC_ALL, "Ru"); // Установка русской локали программы
    std::cout << "Введите количество графических объектов: "; // Запрос количества окружностей
    std::cin >> n; // Ввод количества окружностей
    int const m = n; // Сохранение количества окружностей для создания новых массивов
    std::cout << "Введите радиус окружностей: "; // Запрос радиуса окружностей
    std::cin >> r; // Ввод радиуса окружностей
    if (n <= 0 || r <= 0 || (2 * r) > height || (2 * r) > width) { // Проверка корректности введённых данных
        std::cout << "Ошибка ввода."; // Вывод сообщения об ошибке
        return 0; // Завершение программы при неправильном вводе
    }
    srand(time(NULL)); // Инициализация генератора случайных чисел текущим временем
    float* X = new float[n]; // Создание динамического массива координат X
    float* Y = new float[n]; // Создание динамического массива координат Y
    float* newX = new float[m]; // Создание массива координат X непересекающихся окружностей
    float* newY = new float[m]; // Создание массива координат Y непересекающихся окружностей
    bool* peresechenie = new bool[n]; // Создание массива признаков пересечения окружностей
    for (int i = 0; i < n; i++) { // Цикл генерации координат X
        X[i] = r + rand() % (width - 2 * r); // Генерация случайной координаты X с учётом радиуса
    }
    for (int i = 0; i < n; i++) { // Цикл генерации координат Y
        Y[i] = r + rand() % (height - 2 * r); // Генерация случайной координаты Y с учётом радиуса
    }
    for (int i = 0; i < n; i++) { // Цикл вывода координат всех окружностей
        std::cout << "{" << X[i] << "," << Y[i] << "}" << "\n"; // Вывод координат центра окружности
    }
    for (int i = 0; i < n; i++) { // Перебор всех окружностей
        peresechenie[i] = true; // Предположение, что текущая окружность не пересекается с другими
        for (int j = 0; j < n; j++) { // Перебор остальных окружностей
            if (i != j) { // Проверка, что сравниваются разные окружности
                int x = X[i] - X[j]; // Вычисление разности координат X центров
                int y = Y[i] - Y[j]; // Вычисление разности координат Y центров

                if (x * x + y * y <= 4 * r * r) { // Проверка пересечения или соприкосновения окружностей
                    peresechenie[i] = false; // Отметка о наличии пересечения
                }
            }
        }
    }
    for (int i = 0; i < n; i++) { // Перебор всех окружностей для отбора непересекающихся
        if (peresechenie[i]) { // Проверка, что окружность не пересекается ни с одной другой
            newX[count] = X[i]; // Запись координаты X в новый массив
            newY[count] = Y[i]; // Запись координаты Y в новый массив
            count++; // Увеличение количества непересекающихся окружностей
        }
    }
    std::cout << "Количество непересекающихся окружностей: " << count; // Вывод количества оставшихся окружностей
    sf::String title(L"Окружности"); // Создание заголовка графического окна
    sf::RenderWindow window(sf::VideoMode({ width, height }), title); // Создание графического окна заданного размера
    bool result = false; // Переменная переключения между первоначальным и итоговым изображением
    while (window.isOpen()) { // Главный цикл работы графического окна
        while (const std::optional event = window.pollEvent()) { // Получение и обработка событий окна
            if (event->is<sf::Event::Closed>()) // Проверка события закрытия окна
                window.close(); // Закрытие графического окна

            if (const auto* key = event->getIf<sf::Event::KeyPressed>()) { // Проверка события нажатия клавиши
                if (key->code == sf::Keyboard::Key::Enter) // Проверка нажатия клавиши Enter
                    result = true; // Переключение на итоговое изображение
            }
        }
        window.clear(); // Очистка графического окна перед новой отрисовкой
        if (result == false) { // Проверка, нужно ли показывать первоначальное изображение
            for (int i = 0; i < n; i++) { // Перебор всех первоначальных окружностей
                sf::CircleShape circle(r); // Создание окружности заданного радиуса
                circle.setPosition(sf::Vector2f(X[i] - r, Y[i] - r)); // Установка положения окружности с учётом радиуса
                circle.setFillColor(sf::Color::Cyan); // Установка цвета заливки окружности
                circle.setOutlineThickness(1); // Установка толщины границы окружности
                circle.setOutlineColor(sf::Color::Blue); // Установка цвета границы окружности
                window.draw(circle); // Отображение окружности в графическом окне
            }
        }
        else { // Ветка отображения итогового изображения
            for (int i = 0; i < count; i++) { // Перебор непересекающихся окружностей
                for (int j = i + 1; j < count; j++) { // Выбор следующей окружности для соединения
                    sf::Vertex line[2]; // Создание массива из двух вершин для линии
                    line[0].position = sf::Vector2f(newX[i], newY[i]); // Задание координат начала линии
                    line[1].position = sf::Vector2f(newX[j], newY[j]); // Задание координат конца линии
                    line[0].color = sf::Color::Red; // Установка красного цвета первой вершины
                    line[1].color = sf::Color::Red; // Установка красного цвета второй вершины
                    window.draw(line, 2, sf::PrimitiveType::Lines); // Отрисовка линии между центрами окружностей
                }
            }
            for (int i = 0; i < count; i++) { // Перебор всех непересекающихся окружностей
                sf::CircleShape circle(r); // Создание окружности заданного радиуса
                circle.setPosition(sf::Vector2f(newX[i] - r, newY[i] - r)); // Установка положения окружности
                circle.setFillColor(sf::Color::Cyan); // Установка цвета заливки окружности
                circle.setOutlineThickness(1); // Установка толщины границы окружности
                circle.setOutlineColor(sf::Color::Blue); // Установка цвета границы окружности
                window.draw(circle); // Отображение непересекающейся окружности
            }
        }
        window.display(); // Отображение сформированного изображения в окне
    }
    delete[] X; // Освобождение памяти массива координат X
    delete[] Y; // Освобождение памяти массива координат Y
    delete[] newX; // Освобождение памяти массива новых координат X
    delete[] newY; // Освобождение памяти массива новых координат Y
    delete[] peresechenie; // Освобождение памяти массива признаков пересечения
    return 0; // Завершение программы
}
